// Generate full 100 Topics with complete 20 Easy, 20 Medium, 20 Hard questions each
export function build100JamrainTopics(): JamrainTopicItem[] {
  const result: JamrainTopicItem[] = [];

  TOPIC_NAMES_100.forEach((meta, idx) => {
    const id = `t-${idx + 1}`;
    // Check if we have manual seed
    const manualSeed = BASE_TOPIC_SEEDS.find(s => s.title === meta.title);

    const pool200 = buildPool(meta.title, 200, manualSeed ? manualSeed.seed200 : []);
    const pool400 = buildPool(meta.title, 400, manualSeed ? manualSeed.seed400 : []);
    const pool600 = buildPool(meta.title, 600, manualSeed ? manualSeed.seed600 : []);

    result.push({
      id,
      title: meta.title,
      category: meta.category,
      categoryLabel: meta.catLabel,
      icon: meta.icon,
      color: '#5b45b0',
      description: `تحدي ضخم يضم 60 سؤالاً (20 سهل، 20 متوسط، 20 حده صعب) في ${meta.title}`,
      svgType: meta.svgType,
      pool200,
      pool400,
      pool600,
      questions: {
        left200: pool200[0],
        left400: pool400[0],
        left600: pool600[0],
        right200: pool200[1] || pool200[0],
        right400: pool400[1] || pool400[0],
        right600: pool600[1] || pool600[0]
      }
    });
  });

  return result;
}

export const ALL_100_JAMRAIN_TOPICS: JamrainTopicItem[] = build100JamrainTopics();

// Helper to draw a fresh unrepeated question from the 20-question pool for that topic & difficulty
export function drawRandomQuestionForTopic(
  topic: JamrainTopicItem,
  points: QuestionPoints,
  usedQuestionIds: Set<string>
): JamrainTopicQuestion {
  let pool = points === 200 ? topic.pool200 : points === 400 ? topic.pool400 : topic.pool600;
  if (!pool || pool.length === 0) {
    return {
      points,
      question: `سؤال في مجال ${topic.title} بقيمة ${points} نقطة`,
      answer: `الإجابة المعتمدة لموضوع ${topic.title}`
    };
  }

  // Filter out questions that have already been asked
  const available = pool.filter(q => !q.id || !usedQuestionIds.has(q.id));
  if (available.length > 0) {
    const picked = available[Math.floor(Math.random() * available.length)];
    if (picked.id) usedQuestionIds.add(picked.id);
    return picked;
  }

  // If all 20 were used, recycle random from pool
  const fallback = pool[Math.floor(Math.random() * pool.length)];
  return fallback;
}
