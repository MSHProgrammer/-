import { QuestionPoints } from '../types/jamr';

export interface JamrainTopicQuestion {
  id?: string;
  points: QuestionPoints;
  question: string;
  answer: string;
  hints?: string[];
  options?: string[];
}

export interface JamrainTopicItem {
  id: string;
  title: string;
  category: 'sports' | 'cinema' | 'science' | 'culture' | 'trivia' | 'gaming' | 'islamic' | 'food';
  categoryLabel: string;
  icon: string;
  color: string;
  description: string;
  svgType: 'lion' | 'science' | 'snacks' | 'brain' | 'cup' | 'choices' | 'car' | 'flag' | 'history' | 'camera' | 'music' | 'planet' | 'shield' | 'swords' | 'coffee' | 'gamepad' | 'tv' | 'book' | 'globe' | 'sparkles';
  pool200: JamrainTopicQuestion[]; // 20 Easy questions
  pool400: JamrainTopicQuestion[]; // 20 Medium questions
  pool600: JamrainTopicQuestion[]; // 20 Hard questions
  questions: {
    left200: JamrainTopicQuestion;
    left400: JamrainTopicQuestion;
    left600: JamrainTopicQuestion;
    right200: JamrainTopicQuestion;
    right400: JamrainTopicQuestion;
    right600: JamrainTopicQuestion;
  };
}

